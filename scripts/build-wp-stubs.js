// Builds extension/data/wp-stubs.js: WordPress's functions, classes and constants with
// signatures and short documentation, plus the names of its action and filter hooks.
//
//   node scripts/build-wp-stubs.js [folder with wordpress-stubs.php, actions.json and filters.json]
//
// Sources (downloaded when no folder is given):
//   - php-stubs/wordpress-stubs: declarations taken from WordPress itself (GPL-2.0-or-later)
//   - @wp-hooks/wordpress-core: the list of hooks (GPL-3.0-or-later)
// The result is committed, so normal builds and releases never need this script or the network.
'use strict';

const fs = require('fs');
const os = require('os');
const path = require('path');
const { parseFile } = require('./build-php-stubs.js');

const STUBS_TAG = 'v7.1.2';
const HOOKS_VERSION = '1.13.0';
const SOURCES = {
  'wordpress-stubs.php': `https://raw.githubusercontent.com/php-stubs/wordpress-stubs/${STUBS_TAG}/wordpress-stubs.php`,
  'actions.json': `https://cdn.jsdelivr.net/npm/@wp-hooks/wordpress-core@${HOOKS_VERSION}/hooks/actions.json`,
  'filters.json': `https://cdn.jsdelivr.net/npm/@wp-hooks/wordpress-core@${HOOKS_VERSION}/hooks/filters.json`,
};

function shorten(text, max) {
  const flat = String(text || '').replace(/\s+/g, ' ').trim();
  if (flat.length <= max) return flat;
  const cut = flat.slice(0, max);
  const stop = cut.lastIndexOf('. ');
  return stop > max * 0.5 ? cut.slice(0, stop + 1) : `${cut.replace(/\s+\S*$/, '')}…`;
}

// Documentation is what makes the file big, so functions keep a sentence and a few words per
// parameter, and methods keep their signatures only.
function trimCallable(entry, withDocs) {
  // The stubs write defaults as \false and \ARRAY_A; the leading backslash is noise in a hint.
  entry.s = entry.s.replace(/\\(?=[A-Za-z_])/g, '');
  if (entry.t) entry.t = entry.t.replace(/\\(?=[A-Za-z_])/g, '');
  delete entry.l;
  delete entry.r;
  if (!withDocs) {
    delete entry.d;
    delete entry.p;
    return entry;
  }
  if (entry.d) entry.d = shorten(entry.d, 120);
  if (entry.p) entry.p = entry.p.map((text) => shorten(text.replace(/^Optional\. /, ''), 60));
  return entry;
}

// name -> [description, parameters]
function hooks(file) {
  const out = {};
  for (const hook of JSON.parse(fs.readFileSync(file, 'utf8')).hooks) {
    const params = (hook.doc.tags || [])
      .filter((tag) => tag.name === 'param' && tag.variable)
      .map((tag) => `${(tag.types || []).join('|')} ${tag.variable}`.trim());
    const entry = [shorten(hook.doc.description, 150)];
    if (params.length) entry.push(params.join(', '));
    out[hook.name] = entry;
  }
  return out;
}

async function main() {
  let root = process.argv[2];
  let temp = null;
  if (!root) {
    temp = fs.mkdtempSync(path.join(os.tmpdir(), 'wpstubs-'));
    root = temp;
    for (const [name, url] of Object.entries(SOURCES)) {
      console.log(`Downloading ${name}…`);
      const res = await fetch(url);
      if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
      fs.writeFileSync(path.join(root, name), Buffer.from(await res.arrayBuffer()));
    }
  }

  const out = { f: {}, c: {}, k: {} };
  parseFile(path.join(root, 'wordpress-stubs.php'), out);
  for (const entry of Object.values(out.f)) trimCallable(entry, true);
  for (const cls of Object.values(out.c)) {
    if (cls.d) cls.d = shorten(cls.d, 120);
    delete cls.l;
    for (const method of Object.values(cls.m || {})) trimCallable(method, false);
    for (const prop of Object.values(cls.p || {})) delete prop.d;
  }
  const data = {
    v: `WordPress ${STUBS_TAG.replace(/^v/, '')}`,
    ...out,
    h: { a: hooks(path.join(root, 'actions.json')), f: hooks(path.join(root, 'filters.json')) },
  };

  const header = `// WordPress functions, classes, constants and hook names, generated by scripts/build-wp-stubs.js\n`
    + `// from php-stubs/wordpress-stubs ${STUBS_TAG} and @wp-hooks/wordpress-core ${HOOKS_VERSION}. The declarations and their\n`
    + `// documentation come from WordPress and are licensed GPL-2.0-or-later (the hook list GPL-3.0-or-later).\n`
    + `// See data/LICENSE-wordpress.txt.\n`;
  const body = `${header}window.CPM_WP_STUBS=${JSON.stringify(data)};\n`;
  fs.writeFileSync(path.join(__dirname, '..', 'extension', 'data', 'wp-stubs.js'), body);

  console.log(`${Object.keys(out.f).length} functions, ${Object.keys(out.c).length} classes, ${Object.keys(out.k).length} constants, `
    + `${Object.keys(data.h.a).length} actions, ${Object.keys(data.h.f).length} filters`);
  console.log(`wp-stubs.js: ${(Buffer.byteLength(body) / 1024).toFixed(0)} KB`);
  if (temp) fs.rmSync(temp, { recursive: true, force: true });
}

main().catch((err) => {
  console.error(err.message);
  process.exit(1);
});
